using System.Text;
using System.Text.Json;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.Json;
using Microsoft.AspNetCore.Http.Metadata;
using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.Options;
using Netjes.Routing;

namespace Netjes.TypeGen;

/// <summary>
/// Writes the app's generated TypeScript: zod schemas for page props, shared props, JSON endpoints and page action
/// forms (from the endpoints' metadata), plus typed routes from the page files.
/// </summary>
internal sealed class TypeScriptGenerator(
    EndpointDataSource endpoints,
    IRouteTableProvider routes,
    PageLoaderRegistry loaders,
    TypeGenRegistry registry,
    LayoutLoaderRegistry layoutLoaders,
    IOptions<JsonOptions> json,
    IOptions<NetjesOptions> options)
{
    /// <summary>
    /// Names the generated file declares, imports or uses from the global scope: a C# type of the same name would
    /// shadow them, so its schema is named otherwise.
    /// </summary>
    public static readonly HashSet<string> ReservedExports = new(StringComparer.Ordinal)
    {
        // Declared.
        "pages", "sharedProps", "api", "forms", "layouts", "serverActions", "actionInputs", "actionResults", "route", "routePatterns", "isHref",
        "RouteParams", "RoutePattern", "Route", "Href",
        // Imported.
        "buildHref", "isRouteHref", "serverAction", "SearchParamsInput", "deferred", "z",
        // Globals.
        "Record", "FormData", "Number",
    };

    private const string Header =
        "// Generated by Netjes from the app's C# types and page files. Do not edit: the app rewrites it when it starts in\n" +
        "// Development, and `netjes generate` writes it for CI (`netjes generate --check` fails when it is out of date).\n";

    private static readonly string[] FormContentTypes = ["application/x-www-form-urlencoded", "multipart/form-data"];

    public string Generate()
    {
        var schemas = new ZodSchemas(json.Value.SerializerOptions);
        var table = routes.Current;
        var all = endpoints.Endpoints.OfType<RouteEndpoint>().ToList();

        var pages = table.Pages
            .Select(route => (route.Pattern, Type: PagePropsType(all, route.Pattern)))
            .ToList();
        var sharedType = options.Value.SharedPropsType;
        var api = ApiEntries(all);
        var forms = FormEntries(all);
        var layouts = layoutLoaders.All.Where(l => l.PropsType is not null).Select(l => (l.Segment.Id, Type: l.PropsType!)).ToList();
        var actions = ActionEntries(all);
        var groups = registry.Snapshot();

        foreach (var type in pages.Select(p => p.Type).OfType<Type>()) schemas.Add(type);
        if (sharedType is not null) schemas.Add(sharedType);
        foreach (var (_, request, response) in api)
        {
            if (request is not null) schemas.Add(request);
            if (response is not null) schemas.Add(response);
        }

        foreach (var (_, form) in forms) schemas.Add(form);
        foreach (var (_, type) in layouts) schemas.Add(type);
        foreach (var action in actions)
        {
            if (action.Input is not null) schemas.Add(action.Input);
            if (action.Result is not null) schemas.Add(action.Result);
        }
        foreach (var slot in groups.SelectMany(g => g.Entries).SelectMany(e => e.Slots.Values)) schemas.Add(slot);

        var output = new StringBuilder(Header);
        var declarations = schemas.Declarations();
        output.Append(actions.Count > 0
            ? "import { buildHref, isRouteHref, serverAction, type SearchParamsInput } from 'netjes';\n"
            : "import { buildHref, isRouteHref, type SearchParamsInput } from 'netjes';\n");
        if (schemas.UsesDeferred)
        {
            output.Append("import { deferred } from 'netjes/zod';\n");
        }

        output.Append("import { z } from 'zod';\n\n");
        output.Append(declarations);

        output.Append("\n/** Props of each page by URL pattern, as its C# loader returns them: `definePage(pages['/blog/[slug]'], Page)`. */\n");
        AppendMap(output, "pages", pages.Select(p => (p.Pattern, p.Type switch
        {
            { } type => schemas.Reference(type),
            null when loaders.Contains(p.Pattern) => "z.record(z.string(), z.unknown())",
            null => "z.object({})",
        })));

        output.Append("\n/** `NetjesOptions.UseSharedProps`: `useSharedProps(sharedProps)`. */\n");
        output.Append("export const sharedProps = ").Append(sharedType is null ? "z.unknown()" : schemas.Reference(sharedType)).Append(";\n");

        output.Append("\n/** JSON endpoints by method and route: what they accept and return. */\n");
        AppendMap(output, "api", api.Select(a => (a.Key, Slots(
            ("request", a.Request is null ? null : schemas.Reference(a.Request)),
            ("response", a.Response is null ? null : schemas.Reference(a.Response))))));

        output.Append("\n/** Form fields of page actions (`MapPageAction`), by page pattern. */\n");
        AppendMap(output, "forms", forms.Select(f => (f.Pattern, schemas.Reference(f.Type))));

        if (layouts.Count > 0)
        {
            output.Append("\n/** Props of each layout's C# loader (`MapLayoutLoader`), by folder: `defineLayout(layouts['app/docs'], Layout)`. */\n");
            AppendMap(output, "layouts", layouts.Select(l => (l.Id, schemas.Reference(l.Type))));
        }

        if (actions.Count > 0)
        {
            var inputs = actions
                .Select(a => (a.Name, Schema: a.Input is null ? null : schemas.InputExpression(a.Input)))
                .Where(a => a.Schema is not null)
                .ToDictionary(a => a.Name, a => a.Schema!, StringComparer.Ordinal);
            if (inputs.Count > 0)
            {
                output.Append("\n/** What the server actions below read, where it differs from what their input types write. */\n");
                AppendMap(output, "actionInputs", inputs.Select(i => (i.Key, i.Value)), export: false);
            }

            // Results without a name of their own (anonymous types, lists): a type needs a value to take it from.
            var results = actions
                .Select(a => (a.Name, Schema: a.Result is null ? null : schemas.Reference(a.Result)))
                .Where(a => a.Schema is not null && !IsIdentifier(a.Schema))
                .ToDictionary(a => a.Name, a => a.Schema!, StringComparer.Ordinal);
            if (results.Count > 0)
            {
                output.Append("\n/** The results of the server actions below whose types have no name of their own. */\n");
                AppendMap(output, "actionResults", results.Select(r => (r.Key, r.Value)), export: false);
            }

            output.Append("\n/** Server actions (`MapAction`), typed from their C# signatures: call them, or pass them to `useAction`. */\n");
            AppendMap(output, "serverActions", actions.Select(a => (a.Name, ActionReference(a, schemas, inputs.ContainsKey(a.Name), results.ContainsKey(a.Name)))));
        }

        foreach (var (group, entries) in groups)
        {
            output.Append('\n');
            AppendMap(output, group, entries.Select(e => (e.Key, Slots([.. e.Slots.Select(s => (s.Key, (string?)schemas.Reference(s.Value)))]))));
        }

        AppendRoutes(output, table);
        return output.ToString();
    }

    /// <param name="NoResult">It returns the untyped ServerActionResult (Ok(), Redirect(...), Invalid(...)): no result.</param>
    private sealed record ActionEntry(string Name, Type? Input, bool FormInput, Type? Result, bool NoResult);

    private static List<ActionEntry> ActionEntries(List<RouteEndpoint> all) =>
        [.. all
            .Select(e => (Endpoint: e, Action: e.Metadata.GetMetadata<ServerActionMetadata>()))
            .Where(e => e.Action is not null)
            .Select(e =>
            {
                var accepts = e.Endpoint.Metadata.GetMetadata<IAcceptsMetadata>();
                var json = accepts?.RequestType is not null && IsJson(accepts.ContentTypes);
                var form = accepts is not null && accepts.ContentTypes.Any(t => FormContentTypes.Contains(t, StringComparer.OrdinalIgnoreCase));
                var result = e.Endpoint.Metadata.GetMetadata<ServerActionResultMetadata>();
                return new ActionEntry(
                    e.Action!.Name,
                    json ? accepts!.RequestType : null,
                    !json && form,
                    result?.ResultType,
                    result is { ResultType: null });
            })
            .DistinctBy(a => a.Name)
            .OrderBy(a => a.Name, StringComparer.Ordinal)];

    /// <summary><c>serverAction&lt;Input, Result&gt;("name", { result })</c>: input and result typed when the C# side names them.</summary>
    /// <param name="inputInMap">Its input type is in <c>actionInputs</c>, by its name.</param>
    /// <param name="resultInMap">Its result schema is in <c>actionResults</c>, by its name.</param>
    private static string ActionReference(ActionEntry action, ZodSchemas schemas, bool inputInMap, bool resultInMap)
    {
        var input = inputInMap
            ? $"z.input<typeof actionInputs[{JsonSerializer.Serialize(action.Name)}]>"
            : action.Input is not null && IsIdentifier(schemas.Reference(action.Input))
                ? $"z.input<typeof {schemas.Reference(action.Input)}>"
                : action.FormInput ? "FormData" : action.Input is null ? "void" : "unknown";
        var name = JsonSerializer.Serialize(action.Name);
        var result = resultInMap ? $"actionResults[{name}]" : action.Result is null ? null : schemas.Reference(action.Result);
        var resultType = resultInMap ? $"z.infer<typeof {result}>"
            : result is not null && IsIdentifier(result) ? result
            : action.NoResult ? "void" : "unknown";
        return result is null
            ? $"serverAction<{input}, {resultType}>({name})"
            : $"serverAction<{input}, {resultType}>({name}, {{ result: {result} }})";
    }

    private static bool IsIdentifier(string expression) =>
        expression.Length > 0 && (char.IsLetter(expression[0]) || expression[0] == '_') && expression.All(c => char.IsLetterOrDigit(c) || c == '_');

    private Type? PagePropsType(List<RouteEndpoint> all, string pattern) =>
        all.Where(e => e.Metadata.GetMetadata<PageEndpointMetadata>()?.Pattern == pattern)
            .Where(e => e.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods.Contains(HttpMethods.Get) ?? true)
            .Select(e => e.Metadata.GetMetadata<PagePropsMetadata>()?.PropsType)
            .FirstOrDefault(t => t is not null);

    private static List<(string Key, Type? Request, Type? Response)> ApiEntries(List<RouteEndpoint> all)
    {
        var entries = new List<(string Key, Type? Request, Type? Response)>();
        foreach (var endpoint in all.Where(e => e.Metadata.GetMetadata<PageEndpointMetadata>() is null))
        {
            var produces = endpoint.Metadata.GetOrderedMetadata<IProducesResponseTypeMetadata>();
            var accepts = endpoint.Metadata.GetMetadata<IAcceptsMetadata>();
            var response = produces
                .Where(p => p.StatusCode is >= 200 and < 300 && p.Type is not null && p.Type != typeof(void) && IsJson(p.ContentTypes))
                .Select(p => p.Type)
                .FirstOrDefault();
            var request = accepts?.RequestType is { } body && IsJson(accepts.ContentTypes) ? body : null;
            var isJsonEndpoint = response is not null || request is not null
                || produces.Any(p => p.StatusCode is >= 200 and < 300 && (p.Type is null || p.Type == typeof(void)));
            if (!isJsonEndpoint)
            {
                continue;
            }

            var methods = endpoint.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods ?? [];
            foreach (var method in methods.Where(m => m != HttpMethods.Head))
            {
                entries.Add(($"{method} {endpoint.RoutePattern.RawText}", request, response));
            }
        }

        return [.. entries.DistinctBy(e => e.Key).OrderBy(e => e.Key, StringComparer.Ordinal)];
    }

    private static List<(string Pattern, Type Type)> FormEntries(List<RouteEndpoint> all) =>
        [.. all
            .Where(e => e.Metadata.GetMetadata<PageEndpointMetadata>()?.Pattern is not null)
            .Where(e => e.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods.Contains(HttpMethods.Post) ?? false)
            .Select(e => (Pattern: e.Metadata.GetMetadata<PageEndpointMetadata>()!.Pattern!, Accepts: e.Metadata.GetMetadata<IAcceptsMetadata>()))
            .Where(e => e.Accepts?.RequestType is not null && e.Accepts.ContentTypes.Any(c => FormContentTypes.Contains(c, StringComparer.OrdinalIgnoreCase)))
            .Select(e => (e.Pattern, e.Accepts!.RequestType!))
            .DistinctBy(e => e.Pattern)
            .OrderBy(e => e.Pattern, StringComparer.Ordinal)];

    private static bool IsJson(IEnumerable<string> contentTypes) =>
        contentTypes.Any(c => c.StartsWith("application/json", StringComparison.OrdinalIgnoreCase) || c.EndsWith("+json", StringComparison.OrdinalIgnoreCase));

    private static string Slots(params (string Name, string? Schema)[] slots) =>
        slots.All(s => s.Schema is null) ? "{}" : $"{{ {string.Join(", ", slots.Where(s => s.Schema is not null).Select(s => $"{s.Name}: {s.Schema}"))} }}";

    private static void AppendMap(StringBuilder output, string name, IEnumerable<(string Key, string Value)> entries, bool export = true)
    {
        var list = entries.ToList();
        var declaration = export ? "export const " : "const ";
        if (list.Count == 0)
        {
            output.Append(declaration).Append(name).Append(" = {} as const;\n");
            return;
        }

        output.Append(declaration).Append(name).Append(" = {\n");
        foreach (var (key, value) in list)
        {
            output.Append("  ").Append(JsonSerializer.Serialize(key)).Append(": ").Append(value).Append(",\n");
        }

        output.Append("} as const;\n");
    }

    private static void AppendRoutes(StringBuilder output, RouteTable table)
    {
        output.Append("\n/** Every page's URL pattern and the parameters `route()` needs for it. */\n");
        if (table.Pages.Count == 0)
        {
            output.Append("export type RouteParams = Record<never, never>;\n");
        }
        else
        {
            output.Append("export type RouteParams = {\n");
            foreach (var page in table.Pages)
            {
                var parameters = page.Parameters.Count == 0
                    ? "Record<string, never>"
                    : $"{{ {string.Join("; ", page.Parameters.Select(p => p.Kind switch
                    {
                        RouteParameterKind.Single => $"{p.Name}: string",
                        RouteParameterKind.CatchAll => $"{p.Name}: string[]",
                        _ => $"{p.Name}?: string[]",
                    }))} }}";
                output.Append("  ").Append(JsonSerializer.Serialize(page.Pattern)).Append(": ").Append(parameters).Append(";\n");
            }

            output.Append("};\n");
        }

        var variants = table.Pages.SelectMany(p => UrlTemplates(p.Pattern)).Distinct(StringComparer.Ordinal).ToList();
        output.Append("export type RoutePattern = keyof RouteParams;\n");
        output.Append("/** The URLs the app's pages serve. */\n");
        output.Append("export type Route = ").Append(variants.Count == 0 ? "never" : string.Join(" | ", variants)).Append(";\n");
        output.Append("/** What `<Link href>` and `router.push` accept: the app's routes, with a query or fragment, or another site. */\n");
        output.Append(
            "export type Href = Route | `${Route}?${string}` | `${Route}#${string}` | `?${string}` | `#${string}`" +
            " | `http://${string}` | `https://${string}` | `mailto:${string}` | `tel:${string}`;\n\n");
        output.Append(
            """
            /** The URL of a page, with its parameters encoded: `route('/blog/[slug]', { slug })`. */
            export function route<P extends RoutePattern>(
              pattern: P,
              ...args: {} extends RouteParams[P] ? [params?: RouteParams[P], search?: SearchParamsInput] : [params: RouteParams[P], search?: SearchParamsInput]
            ): Href {
              return buildHref(pattern, args[0] ?? {}, args[1]) as Href;
            }

            """.ReplaceLineEndings("\n"));
        output.Append("/** Every page's URL pattern. */\n");
        output.Append("export const routePatterns = [")
            .Append(string.Join(", ", table.Pages.Select(p => JsonSerializer.Serialize(p.Pattern))))
            .Append("] as const;\n\n");
        output.Append(
            """
            /** Whether a URL that comes from data (a CMS, shared props) is one of the app's pages or another site. */
            export function isHref(value: string): value is Href {
              return isRouteHref(value, routePatterns);
            }

            /** Checks such a URL at the boundary: `<Link href={Href.parse(item.href)}>`. */
            export const Href = z.custom<Href>((value) => typeof value === 'string' && isHref(value), 'Not a URL this app serves');

            declare module 'netjes' {
              interface Register {
                href: Href;
              }
            }

            """.ReplaceLineEndings("\n"));
    }

    /// <summary>TypeScript literal types for the URLs a pattern matches: '/about', `/blog/${string}`.</summary>
    private static IEnumerable<string> UrlTemplates(string pattern)
    {
        var variants = new List<string> { "" };
        foreach (var segment in pattern.Split('/', StringSplitOptions.RemoveEmptyEntries))
        {
            if (segment.StartsWith("[[...", StringComparison.Ordinal))
            {
                variants = [.. variants.SelectMany(v => new[] { v, v + "/${string}" })];
            }
            else if (segment.StartsWith('['))
            {
                variants = [.. variants.Select(v => v + "/${string}")];
            }
            else
            {
                var escaped = segment.Replace("\\", "\\\\").Replace("`", "\\`").Replace("${", "\\${").Replace("'", "\\'");
                variants = [.. variants.Select(v => v + "/" + escaped)];
            }
        }

        return variants.Select(v => v.Length == 0 ? "'/'" : v.Contains("${string}", StringComparison.Ordinal) ? $"`{v}`" : $"'{v}'");
    }
}
