using System.Text;
using System.Text.Json;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.Json;
using Microsoft.AspNetCore.Http.Metadata;
using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.Options;
using Netjes.Routing;

namespace Netjes.TypeGen;

/// <summary>
/// Writes the app's generated TypeScript: zod schemas for page props, shared props, JSON endpoints and page action
/// forms (from the endpoints' metadata), typed URLs of the app's endpoints, plus typed routes from the page files.
/// </summary>
internal sealed class TypeScriptGenerator(
    EndpointDataSource endpoints,
    IRouteTableProvider routes,
    PageLoaderRegistry loaders,
    TypeGenRegistry registry,
    LayoutLoaderRegistry layoutLoaders,
    RouteSources sources,
    IOptions<JsonOptions> json,
    IOptions<NetjesOptions> options)
{
    /// <summary>
    /// Names the generated file declares, imports or uses from the global scope: a C# type of the same name would
    /// shadow them, so its schema is named otherwise.
    /// </summary>
    public static readonly HashSet<string> ReservedExports = new(StringComparer.Ordinal)
    {
        // Declared.
        "pages", "sharedProps", "api", "forms", "layouts", "serverActions", "actionInputs", "actionResults", "route", "routePatterns", "isHref",
        "RouteParams", "RoutePattern", "Route", "Href", "EndpointParams", "EndpointKey", "endpointTemplates", "endpointUrl",
        // Imported.
        "buildEndpointUrl", "buildHref", "isRouteHref", "serverAction", "SearchParamsInput", "deferred", "z",
        // Globals.
        "Record", "FormData", "Number",
    };

    /// <summary>
    /// What a page package's file declares or imports besides the names of the app's: its typed links, and what it calls
    /// in <c>netjes</c>. Reserved in that file only, so a package renames none of the app's schemas.
    /// </summary>
    public static readonly HashSet<string> PackageReservedExports = new(ReservedExports.Concat(
    [
        // Declared.
        "MountHref", "Link", "Form", "SubmitButton", "useRouter", "usePathname", "useHref",
        // Imported.
        "isHrefShape", "mounted",
    ]), StringComparer.Ordinal);

    private const string Header =
        "// Generated by Netjes from the app's C# types and page files. Do not edit: the app rewrites it when it starts in\n" +
        "// Development, and `netjes generate` writes it for CI (`netjes generate --check` fails when it is out of date).\n";

    private const string PackageHeader =
        "// Generated by Netjes from a page package's C# types and page files, below the package's mount, so it is the same\n" +
        "// wherever an app mounts it. Do not edit: the app the package is developed in rewrites it when it starts in\n" +
        "// Development (`.WriteTypes()` on the mount), and `netjes generate` writes it for CI (`netjes generate --check` fails\n" +
        "// when it is out of date).\n";

    private static readonly string[] FormContentTypes = ["application/x-www-form-urlencoded", "multipart/form-data"];

    /// <summary>The app's file: every page's route, the packages' included, and the schemas of the app's own endpoints.</summary>
    public string Generate() => GenerateFile(package: null);

    /// <summary>
    /// A mounted page package's own file: the schemas of its loaders, page actions, layout loaders, server actions and
    /// endpoints, and its routes, keyed below the mount and without the prefix's parameters, and the links of
    /// <c>mounted()</c> typed by them.
    /// </summary>
    public string Generate(MountedPackage package) => GenerateFile(package);

    private string GenerateFile(MountedPackage? package)
    {
        // A page package's exports are in its own file and in the app's, where the app's own are too.
        var groups = registry.Snapshot().Where(g => package is null || g.Owner == package.Name).ToList();
        // A registered export's name is taken in the file that holds it, so a C# type of that name gets another.
        var schemas = new ZodSchemas(
            json.Value.SerializerOptions,
            new HashSet<string>((package is null ? ReservedExports : PackageReservedExports).Concat(groups.Select(g => g.Group)), StringComparer.Ordinal));
        var table = routes.Current;
        var all = endpoints.Endpoints.OfType<RouteEndpoint>().ToList();
        // A page package's pages are routes of the app, but their schemas are in the package's own file.
        var own = all.Where(e => PackageOf(e) == package?.Name).ToList();
        var prefix = package?.Mount.Prefix;
        string Key(string pattern) => prefix?.Below(pattern) ?? pattern;

        // The app links to every page, the packages' included; a package links to its own pages, below its mount.
        var linked = (package is null ? table.Pages : table.Pages.Where(route => sources.PackageOf(route)?.Name == package.Name))
            .Select(route => (Key: Key(route.Pattern), Parameters: (IReadOnlyList<RouteParameter>)
                [.. route.Parameters.Where(p => prefix is null || !prefix.Parameters.Contains(p.Name, StringComparer.OrdinalIgnoreCase))]))
            .OrderBy(route => route.Key, StringComparer.Ordinal)
            .ToList();
        var pages = table.Pages
            .Where(route => sources.PackageOf(route)?.Name == package?.Name)
            .Select(route => (Key: Key(route.Pattern), route.Pattern, Type: PagePropsType(all, route.Pattern)))
            .OrderBy(p => p.Key, StringComparer.Ordinal)
            .ToList();
        var sharedType = package is null ? options.Value.SharedPropsType : null;
        var api = ApiEntries(own, prefix);
        var forms = FormEntries(own).Select(f => (Key: Key(f.Pattern), f.Type)).OrderBy(f => f.Key, StringComparer.Ordinal).ToList();
        var layouts = layoutLoaders.All
            .Where(l => l.PropsType is not null && sources.OwnerOf(l.Segment.Layout)?.Name == package?.Name)
            .Select(l => (Key: package?.FolderInThePackage(l.Segment.Id, sources.AppDirectory) ?? l.Segment.Id, Type: l.PropsType!))
            .OrderBy(l => l.Key, StringComparer.Ordinal)
            .ToList();
        var actions = ActionEntries(own);

        foreach (var type in pages.Select(p => p.Type).OfType<Type>()) schemas.Add(type);
        if (sharedType is not null) schemas.Add(sharedType);
        foreach (var (_, request, response) in api)
        {
            if (request is not null) schemas.Add(request);
            if (response is not null) schemas.Add(response);
        }

        foreach (var (_, form) in forms) schemas.Add(form);
        foreach (var (_, type) in layouts) schemas.Add(type);
        foreach (var action in actions)
        {
            if (action.Input is not null) schemas.Add(action.Input);
            if (action.Result is not null) schemas.Add(action.Result);
        }
        foreach (var slot in groups.Where(g => package is not null || g.Owner is null).SelectMany(g => g.Entries).SelectMany(e => e.Slots)) schemas.Add(slot.Value);
        // In the app's file, a page package's export yields: the app's own types keep the names they have without the package.
        foreach (var slot in groups.Where(g => package is null && g.Owner is not null).SelectMany(g => g.Entries).SelectMany(e => e.Slots)) schemas.AddYielding(slot.Value);

        var output = new StringBuilder(package is null ? Header : PackageHeader);
        var declarations = schemas.Declarations();
        var imports = package is null
            ? new List<string> { "buildEndpointUrl", "buildHref", "isRouteHref" }
            : ["buildEndpointUrl", "buildHref", "isHrefShape", "mounted"];
        if (actions.Count > 0)
        {
            imports.Add("serverAction");
        }

        output.Append("import { ").Append(string.Join(", ", imports)).Append(", type SearchParamsInput } from 'netjes';\n");
        if (schemas.UsesDeferred)
        {
            output.Append("import { deferred } from 'netjes/zod';\n");
        }

        output.Append("import { z } from 'zod';\n\n");
        // Before the declarations: a schema with an Href property reads Href as the module loads.
        AppendHref(output, linked.Select(l => l.Key), package is not null);
        if (declarations.Length > 0)
        {
            output.Append('\n').Append(declarations);
        }

        output.Append(package is null
            ? "\n/** Props of each page by URL pattern, as its C# loader returns them: `definePage(pages['/blog/[slug]'], Page)`. */\n"
            : "\n/** Props of each of the package's pages by URL pattern below the mount, as its C# loader returns them: `definePage(pages['/articles/[slug]'], Page)`. */\n");
        AppendMap(output, "pages", pages.Select(p => (p.Key, p.Type switch
        {
            { } type => schemas.Reference(type),
            null when loaders.Contains(p.Pattern) => "z.record(z.string(), z.unknown())",
            null => "z.object({})",
        })));

        output.Append(package is null
            ? "\n/** `NetjesOptions.UseSharedProps`: `useSharedProps(sharedProps)`. */\n"
            : "\n/** The app's shared props (`NetjesOptions.UseSharedProps`), which a page package does not know. */\n");
        output.Append("export const sharedProps = ").Append(sharedType is null ? "z.unknown()" : schemas.Reference(sharedType)).Append(";\n");

        output.Append(package is null
            ? "\n/** JSON endpoints by method and route: what they accept and return. */\n"
            : "\n/** JSON endpoints mapped through the mount, by method and route below it: what they accept and return. */\n");
        AppendMap(output, "api", api.Select(a => (a.Key, Slots(
            ("request", a.Request is null ? null : schemas.Reference(a.Request)),
            ("response", a.Response is null ? null : schemas.Reference(a.Response))))));
        EndpointUrls.Append(output, EndpointUrls.Entries(own, IsInTheApiMap, prefix), package is not null);

        output.Append(package is null
            ? "\n/** Form fields of page actions (`MapPageAction`), by page pattern. */\n"
            : "\n/** Form fields of the package's page actions (`MapPageAction` on the mount), by page pattern below the mount. */\n");
        AppendMap(output, "forms", forms.Select(f => (f.Key, schemas.Reference(f.Type))));

        if (layouts.Count > 0)
        {
            output.Append(package is null
                ? "\n/** Props of each layout's C# loader (`MapLayoutLoader`), by folder: `defineLayout(layouts['app/docs'], Layout)`. */\n"
                : "\n/** Props of each layout's C# loader (`MapLayoutLoader` on the mount), by folder in the package: `defineLayout(layouts['app/(center)'], Layout)`. */\n");
            AppendMap(output, "layouts", layouts.Select(l => (l.Key, schemas.Reference(l.Type))));
        }

        if (actions.Count > 0)
        {
            var inputs = actions
                .Select(a => (a.Name, Schema: a.Input is null ? null : schemas.InputExpression(a.Input)))
                .Where(a => a.Schema is not null)
                .ToDictionary(a => a.Name, a => a.Schema!, StringComparer.Ordinal);
            if (inputs.Count > 0)
            {
                output.Append("\n/** What the server actions below read, where it differs from what their input types write. */\n");
                AppendMap(output, "actionInputs", inputs.Select(i => (i.Key, i.Value)), export: false);
            }

            // Results without a name of their own (anonymous types, lists): a type needs a value to take it from.
            var results = actions
                .Select(a => (a.Name, Schema: a.Result is null ? null : schemas.Reference(a.Result)))
                .Where(a => a.Schema is not null && !IsIdentifier(a.Schema))
                .ToDictionary(a => a.Name, a => a.Schema!, StringComparer.Ordinal);
            if (results.Count > 0)
            {
                output.Append("\n/** The results of the server actions below whose types have no name of their own. */\n");
                AppendMap(output, "actionResults", results.Select(r => (r.Key, r.Value)), export: false);
            }

            output.Append(package is null
                ? "\n/** Server actions (`MapAction`), typed from their C# signatures: call them, or pass them to `useAction`. */\n"
                : "\n/** The package's server actions (`MapAction` on the mount), typed from their C# signatures: call them, or pass them to `useAction`. */\n");
            AppendMap(output, "serverActions", actions.Select(a => (a.Name, ActionReference(a, schemas, inputs.ContainsKey(a.Name), results.ContainsKey(a.Name)))));
        }

        foreach (var (group, _, entries) in groups)
        {
            output.Append('\n');
            // Slot names are quoted as keys are: a registered name is text, never code.
            AppendMap(output, group, entries.Select(e => (e.Key, Slots([.. e.Slots.Select(s => (JsonSerializer.Serialize(s.Key), (string?)schemas.Reference(s.Value)))]))));
        }

        AppendRoutes(output, linked, package?.Name);
        return output.ToString();
    }

    /// <summary>The page package an endpoint is of: its file pages and what its mount maps; null for the app's.</summary>
    private static string? PackageOf(RouteEndpoint endpoint) => endpoint.Metadata.GetMetadata<PagePackageEndpointMetadata>()?.Package;

    /// <param name="NoResult">It returns the untyped ServerActionResult (Ok(), Redirect(...), Invalid(...)): no result.</param>
    private sealed record ActionEntry(string Name, Type? Input, bool FormInput, Type? Result, bool NoResult);

    private static List<ActionEntry> ActionEntries(List<RouteEndpoint> all) =>
        [.. all
            .Select(e => (Endpoint: e, Action: e.Metadata.GetMetadata<ServerActionMetadata>()))
            .Where(e => e.Action is not null)
            .Select(e =>
            {
                var accepts = e.Endpoint.Metadata.GetMetadata<IAcceptsMetadata>();
                var json = accepts?.RequestType is not null && IsJson(accepts.ContentTypes);
                var form = accepts is not null && accepts.ContentTypes.Any(t => FormContentTypes.Contains(t, StringComparer.OrdinalIgnoreCase));
                var result = e.Endpoint.Metadata.GetMetadata<ServerActionResultMetadata>();
                return new ActionEntry(
                    e.Action!.Name,
                    json ? accepts!.RequestType : null,
                    !json && form,
                    result?.ResultType,
                    result is { ResultType: null });
            })
            .DistinctBy(a => a.Name)
            .OrderBy(a => a.Name, StringComparer.Ordinal)];

    /// <summary><c>serverAction&lt;Input, Result&gt;("name", { result })</c>: input and result typed when the C# side names them.</summary>
    /// <param name="inputInMap">Its input type is in <c>actionInputs</c>, by its name.</param>
    /// <param name="resultInMap">Its result schema is in <c>actionResults</c>, by its name.</param>
    private static string ActionReference(ActionEntry action, ZodSchemas schemas, bool inputInMap, bool resultInMap)
    {
        var input = inputInMap
            ? $"z.input<typeof actionInputs[{JsonSerializer.Serialize(action.Name)}]>"
            : action.Input is not null && IsIdentifier(schemas.Reference(action.Input))
                ? $"z.input<typeof {schemas.Reference(action.Input)}>"
                : action.FormInput ? "FormData" : action.Input is null ? "void" : "unknown";
        var name = JsonSerializer.Serialize(action.Name);
        var result = resultInMap ? $"actionResults[{name}]" : action.Result is null ? null : schemas.Reference(action.Result);
        var resultType = resultInMap ? $"z.infer<typeof {result}>"
            : result is not null && IsIdentifier(result) ? result
            : action.NoResult ? "void" : "unknown";
        return result is null
            ? $"serverAction<{input}, {resultType}>({name})"
            : $"serverAction<{input}, {resultType}>({name}, {{ result: {result} }})";
    }

    private static bool IsIdentifier(string expression) =>
        expression.Length > 0 && (char.IsLetter(expression[0]) || expression[0] == '_') && expression.All(c => char.IsLetterOrDigit(c) || c == '_');

    private Type? PagePropsType(List<RouteEndpoint> all, string pattern) =>
        all.Where(e => e.Metadata.GetMetadata<PageEndpointMetadata>()?.Pattern == pattern)
            .Where(e => e.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods.Contains(HttpMethods.Get) ?? true)
            .Select(e => e.Metadata.GetMetadata<PagePropsMetadata>()?.PropsType)
            .FirstOrDefault(t => t is not null);

    /// <param name="mount">The prefix of the page package whose endpoints these are: their keys are the routes below it.</param>
    private static List<(string Key, Type? Request, Type? Response)> ApiEntries(List<RouteEndpoint> all, MountPrefix? mount)
    {
        var entries = new List<(string Key, Type? Request, Type? Response)>();
        foreach (var endpoint in all.Where(e => e.Metadata.GetMetadata<PageEndpointMetadata>() is null))
        {
            if (JsonContract(endpoint) is not var (request, response))
            {
                continue;
            }

            var methods = endpoint.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods ?? [];
            foreach (var method in methods.Where(m => m != HttpMethods.Head))
            {
                entries.Add(($"{method} {EndpointUrls.Route(endpoint.RoutePattern, mount)}", request, response));
            }
        }

        return [.. entries.DistinctBy(e => e.Key).OrderBy(e => e.Key, StringComparer.Ordinal)];
    }

    /// <summary>Whether the endpoint has keys in the <c>api</c> map: a JSON endpoint that is no page.</summary>
    public static bool IsInTheApiMap(RouteEndpoint endpoint) =>
        endpoint.Metadata.GetMetadata<PageEndpointMetadata>() is null && JsonContract(endpoint) is not null;

    /// <summary>
    /// The JSON body an endpoint accepts and the JSON it answers with, or null for an endpoint that is no JSON endpoint:
    /// it declares neither, and no bodiless 2xx (<c>TypedResults.NoContent()</c>) either.
    /// </summary>
    private static (Type? Request, Type? Response)? JsonContract(RouteEndpoint endpoint)
    {
        var produces = endpoint.Metadata.GetOrderedMetadata<IProducesResponseTypeMetadata>();
        var accepts = endpoint.Metadata.GetMetadata<IAcceptsMetadata>();
        var response = produces
            .Where(p => p.StatusCode is >= 200 and < 300 && p.Type is not null && p.Type != typeof(void) && IsJson(p.ContentTypes))
            .Select(p => p.Type)
            .FirstOrDefault();
        var request = accepts?.RequestType is { } body && IsJson(accepts.ContentTypes) ? body : null;
        return response is not null || request is not null
            || produces.Any(p => p.StatusCode is >= 200 and < 300 && (p.Type is null || p.Type == typeof(void)))
            ? (request, response)
            : null;
    }

    private static List<(string Pattern, Type Type)> FormEntries(List<RouteEndpoint> all) =>
        [.. all
            .Where(e => e.Metadata.GetMetadata<PageEndpointMetadata>()?.Pattern is not null)
            .Where(e => e.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods.Contains(HttpMethods.Post) ?? false)
            .Select(e => (Pattern: e.Metadata.GetMetadata<PageEndpointMetadata>()!.Pattern!, Accepts: e.Metadata.GetMetadata<IAcceptsMetadata>()))
            .Where(e => e.Accepts?.RequestType is not null && e.Accepts.ContentTypes.Any(c => FormContentTypes.Contains(c, StringComparer.OrdinalIgnoreCase)))
            .Select(e => (e.Pattern, e.Accepts!.RequestType!))
            .DistinctBy(e => e.Pattern)
            .OrderBy(e => e.Pattern, StringComparer.Ordinal)];

    private static bool IsJson(IEnumerable<string> contentTypes) =>
        contentTypes.Any(c => c.StartsWith("application/json", StringComparison.OrdinalIgnoreCase) || c.EndsWith("+json", StringComparison.OrdinalIgnoreCase));

    private static string Slots(params (string Name, string? Schema)[] slots) =>
        slots.All(s => s.Schema is null) ? "{}" : $"{{ {string.Join(", ", slots.Where(s => s.Schema is not null).Select(s => $"{s.Name}: {s.Schema}"))} }}";

    private static void AppendMap(StringBuilder output, string name, IEnumerable<(string Key, string Value)> entries, bool export = true)
    {
        var list = entries.ToList();
        var declaration = export ? "export const " : "const ";
        if (list.Count == 0)
        {
            output.Append(declaration).Append(name).Append(" = {} as const;\n");
            return;
        }

        output.Append(declaration).Append(name).Append(" = {\n");
        foreach (var (key, value) in list)
        {
            output.Append("  ").Append(JsonSerializer.Serialize(key)).Append(": ").Append(value).Append(",\n");
        }

        output.Append("} as const;\n");
    }

    /// <summary>
    /// The <c>Href</c> schema, which checks a URL against the pages, and what it calls. A page package's checks the shape
    /// alone: it cannot know the app's pages, and a URL from the C# side is the app's, the mount included.
    /// </summary>
    private static void AppendHref(StringBuilder output, IEnumerable<string> patterns, bool package)
    {
        output.Append(package ? "/** Every page's URL pattern, below the mount. */\n" : "/** Every page's URL pattern. */\n");
        output.Append("export const routePatterns = [")
            .Append(string.Join(", ", patterns.Select(p => JsonSerializer.Serialize(p))))
            .Append("] as const;\n\n");
        output.Append(package
            ? """
              /**
               * Whether a URL that comes from data (a CMS, the C# side) has the shape of a link: a path, a link within the page,
               * or another site. A page package cannot know the app's pages, so it checks no more: a C# `Netjes.Href` is a URL
               * of the app, the mount in it.
               */
              export function isHref(value: string): value is Href {
                return isHrefShape(value);
              }

              /** Checks such a URL at the boundary, for the `Link` from 'netjes': `<Link href={Href.parse(item.href)}>`. The schemas below use it for each C# `Netjes.Href`. */
              export const Href = z.custom<Href>((value) => typeof value === 'string' && isHref(value), 'Not a link');

              """.ReplaceLineEndings("\n")
            : """
              /** Whether a URL that comes from data (a CMS, shared props) is one of the app's pages or another site. */
              export function isHref(value: string): value is Href {
                return isRouteHref(value, routePatterns);
              }

              /** Checks such a URL at the boundary: `<Link href={Href.parse(item.href)}>`. The schemas below use it for each C# `Netjes.Href`. */
              export const Href = z.custom<Href>((value) => typeof value === 'string' && isHref(value), 'Not a URL this app serves');

              """.ReplaceLineEndings("\n"));
    }

    /// <summary>
    /// The route types and <c>route()</c>, last: <c>isHref</c> and the <c>Href</c> schema name the <c>Href</c> type
    /// before its declaration, as TypeScript allows for a type. A page package's routes are below its mount, and its file
    /// ends with the links of <c>mounted()</c>, typed by them, where the app's registers its <c>Href</c> with <c>netjes</c>.
    /// </summary>
    /// <param name="pages">Each page's URL pattern and the parameters <c>route()</c> needs for it.</param>
    /// <param name="package">The npm name of the page package whose file this is; null for the app's.</param>
    private static void AppendRoutes(StringBuilder output, IReadOnlyList<(string Pattern, IReadOnlyList<RouteParameter> Parameters)> pages, string? package)
    {
        output.Append("\n/** Every page's URL pattern and the parameters `route()` needs for it. */\n");
        if (pages.Count == 0)
        {
            output.Append("export type RouteParams = Record<never, never>;\n");
        }
        else
        {
            output.Append("export type RouteParams = {\n");
            foreach (var page in pages)
            {
                var parameters = page.Parameters.Count == 0
                    ? "Record<string, never>"
                    : $"{{ {string.Join("; ", page.Parameters.Select(p => p.Kind switch
                    {
                        RouteParameterKind.Single => $"{p.Name}: string",
                        RouteParameterKind.CatchAll => $"{p.Name}: string[]",
                        _ => $"{p.Name}?: string[]",
                    }))} }}";
                output.Append("  ").Append(JsonSerializer.Serialize(page.Pattern)).Append(": ").Append(parameters).Append(";\n");
            }

            output.Append("};\n");
        }

        var variants = pages.SelectMany(p => UrlTemplates(p.Pattern)).Distinct(StringComparer.Ordinal).ToList();
        output.Append("export type RoutePattern = keyof RouteParams;\n");
        output.Append(package is null ? "/** The URLs the app's pages serve. */\n" : "/** The URLs the package's pages serve, below the mount. */\n");
        output.Append("export type Route = ").Append(variants.Count == 0 ? "never" : string.Join(" | ", variants)).Append(";\n");
        if (package is not null)
        {
            AppendMountedRoutes(output, package);
            return;
        }

        output.Append("/** What `<Link href>` and `router.push` accept: the app's routes, with a query or fragment, or another site. */\n");
        output.Append(
            "export type Href = Route | `${Route}?${string}` | `${Route}#${string}` | `?${string}` | `#${string}`" +
            " | `http://${string}` | `https://${string}` | `mailto:${string}` | `tel:${string}`;\n\n");
        output.Append(
            """
            /**
             * The URL of a page, with its parameters encoded: `route('/blog/[slug]', { slug })`. The third argument is the
             * query, and `{ hash }` in the fourth adds a fragment: `route('/docs/[...path]', { path }, undefined, { hash: 'keys' })`.
             */
            export function route<P extends RoutePattern>(
              pattern: P,
              ...args: {} extends RouteParams[P]
                ? [params?: RouteParams[P], search?: SearchParamsInput, options?: { hash?: string | undefined }]
                : [params: RouteParams[P], search?: SearchParamsInput, options?: { hash?: string | undefined }]
            ): Href {
              return buildHref(pattern, args[0] ?? {}, args[1], args[2]) as Href;
            }

            declare module 'netjes' {
              interface Register {
                href: Href;
              }
            }

            """.ReplaceLineEndings("\n"));
    }

    /// <summary>
    /// A page package's link types and <c>route()</c>, below its mount, and the links of <c>mounted()</c> typed by them.
    /// Its <c>Href</c> is the app's, as the core <c>Link</c> takes it: the file registers none, so the app's file and the
    /// package's type-check in one program.
    /// </summary>
    private static void AppendMountedRoutes(StringBuilder output, string package)
    {
        output.Append(
            """
            /** What this file's `Link`, `Form`, `SubmitButton` and `useRouter` take: the package's routes below the mount, with a query or fragment. */
            export type MountHref = Route | `${Route}?${string}` | `${Route}#${string}` | `?${string}` | `#${string}`;
            /**
             * A URL from data, typed as the app's links are: the C# side sends one of the app's URLs, the mount in it, or
             * another site's. Link to it with the `Link` from 'netjes', which puts no mount in front.
             */
            export type Href = import('netjes').Href;

            /**
             * The URL of one of the package's pages below the mount, with its parameters encoded: `route('/articles/[slug]', { slug })`,
             * for this file's `Link` and `useRouter`, which put the mount in front. The third argument is the query, and
             * `{ hash }` in the fourth adds a fragment.
             */
            export function route<P extends RoutePattern>(
              pattern: P,
              ...args: {} extends RouteParams[P]
                ? [params?: RouteParams[P], search?: SearchParamsInput, options?: { hash?: string | undefined }]
                : [params: RouteParams[P], search?: SearchParamsInput, options?: { hash?: string | undefined }]
            ): MountHref {
              return buildHref(pattern, args[0] ?? {}, args[1], args[2]) as MountHref;
            }

            /**
             * Links, forms and router hooks below the package's mount, wherever the app mounts it: `<Link href={route('/')}>`.
             * `useHref` gives a URL below the mount, of a page or of an endpoint (`endpointUrl()`), for a plain `<a>` or a `fetch`.
             */

            """.ReplaceLineEndings("\n"));
        output.Append("export const { Link, Form, SubmitButton, useRouter, usePathname, useHref } = mounted<MountHref>(")
            .Append(JsonSerializer.Serialize(package))
            .Append(");\n");
    }

    /// <summary>TypeScript literal types for the URLs a pattern matches: '/about', `/blog/${string}`.</summary>
    private static IEnumerable<string> UrlTemplates(string pattern)
    {
        var variants = new List<string> { "" };
        foreach (var segment in pattern.Split('/', StringSplitOptions.RemoveEmptyEntries))
        {
            if (segment.StartsWith("[[...", StringComparison.Ordinal))
            {
                variants = [.. variants.SelectMany(v => new[] { v, v + "/${string}" })];
            }
            else if (segment.StartsWith('['))
            {
                variants = [.. variants.Select(v => v + "/${string}")];
            }
            else
            {
                var escaped = segment.Replace("\\", "\\\\").Replace("`", "\\`").Replace("${", "\\${").Replace("'", "\\'");
                variants = [.. variants.Select(v => v + "/" + escaped)];
            }
        }

        return variants.Select(v => v.Length == 0 ? "'/'" : v.Contains("${string}", StringComparison.Ordinal) ? $"`{v}`" : $"'{v}'");
    }
