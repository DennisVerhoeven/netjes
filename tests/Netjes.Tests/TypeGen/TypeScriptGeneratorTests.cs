using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Extensions.DependencyInjection;
using Netjes.Tests.Endpoints;
using Netjes.TypeGen;

namespace Netjes.Tests.TypeGen;

public class TypeScriptGeneratorTests
{
    public sealed record PostDetail(string Slug, string Title);

    public sealed record PostProps(PostDetail Post);

    public sealed record SiteProps(string SiteName);

    public sealed record Item(int Id, string Name);

    public sealed record NewItem(string Name);

    public sealed record ContactForm(string? Name, string? Message);

    public sealed record PostSummary(string Slug);

    public sealed record PostPageProps(PostDetail Post, Deferred<IReadOnlyList<PostSummary>> Related);

    public sealed record DocsLayoutProps(IReadOnlyList<string> Toc);

    public sealed record LikeInput(string Slug);

    public sealed record Likes(string Slug, int Count);

    public sealed record CreatePost(string Title, string? Subtitle, string Body = "")
    {
        public int Length => Title.Length;
    }

    private static async Task<string> GenerateAsync(TestApp app) =>
        app.App.Services.GetRequiredService<TypeScriptGenerator>().Generate();

    [Fact]
    public async Task Generate_StartsWithTheHeaderAndImports()
    {
        await using var app = await TestApp.StartAsync(["app/page.tsx"]);

        var output = await GenerateAsync(app);

        Assert.StartsWith("// Generated by Netjes", output);
        Assert.Contains("import { buildHref, isRouteHref, type SearchParamsInput } from 'netjes';\nimport { z } from 'zod';\n", output);
    }

    [Fact]
    public async Task Generate_PagePropsFromLoaders_AreNamedSchemasInThePagesMap()
    {
        await using var app = await TestApp.StartAsync(
            ["app/blog/[slug]/page.tsx", "app/about/page.tsx", "app/raw/page.tsx"],
            map: a =>
            {
                a.MapPageLoader("/blog/[slug]", (string slug) => Page.Props(new PostProps(new PostDetail(slug, "T"))));
                a.MapPageLoader("/raw", () => TypedResults.Ok());
            });

        var output = await GenerateAsync(app);

        Assert.Contains("export const PostDetail = z.object({\n  slug: z.string(),\n  title: z.string(),\n});", output);
        Assert.Contains("export const PostProps = z.object({\n  post: PostDetail,\n});", output);
        Assert.Contains(
            """
            export const pages = {
              "/about": z.object({}),
              "/blog/[slug]": PostProps,
              "/raw": z.record(z.string(), z.unknown()),
            } as const;
            """.ReplaceLineEndings("\n"),
            output);
    }

    [Fact]
    public async Task Generate_TypedSharedProps_AreExported()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"], configure: o => o.UseSharedProps(_ => ValueTask.FromResult(new SiteProps("Demo"))));

        var output = await GenerateAsync(app);

        Assert.Contains("export const sharedProps = SiteProps;", output);
    }

    [Fact]
    public async Task Generate_WithoutTypedSharedProps_ExportsUnknown()
    {
        await using var app = await TestApp.StartAsync(["app/page.tsx"]);

        Assert.Contains("export const sharedProps = z.unknown();", await GenerateAsync(app));
    }

    [Fact]
    public async Task Generate_JsonEndpoints_DescribeTheirRequestAndResponse()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a =>
            {
                a.MapGet("/api/items/{id}", (int id) => TypedResults.Ok(new Item(id, "a")));
                a.MapPost("/api/items", (NewItem item) => TypedResults.Created("/api/items/1", new Item(1, item.Name)));
                a.MapDelete("/api/items/{id}", (int id) => TypedResults.NoContent());
                a.MapGet("/plain", () => "text");
            });

        var output = await GenerateAsync(app);

        Assert.Contains(
            """
            export const api = {
              "DELETE /api/items/{id}": {},
              "GET /api/items/{id}": { response: Item },
              "POST /api/items": { request: NewItem, response: Item },
            } as const;
            """.ReplaceLineEndings("\n"),
            output);
        Assert.DoesNotContain("/plain", output);
    }

    [Fact]
    public async Task Generate_PageActionFormFields_AreInTheFormsMap()
    {
        await using var app = await TestApp.StartAsync(
            ["app/contact/page.tsx"],
            map: a => a.MapPageAction("/contact", ([FromForm] ContactForm form) => Page.Redirect("/thanks")));

        var output = await GenerateAsync(app);

        Assert.Contains("export const forms = {\n  \"/contact\": ContactForm,\n} as const;", output);
        Assert.Contains("export const ContactForm = z.object({\n  name: z.string().nullable(),\n  message: z.string().nullable(),\n});", output);
    }

    [Fact]
    public async Task Generate_Routes_AreTypedWithTheirParameters()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx", "app/about/page.tsx", "app/blog/[slug]/page.tsx", "app/docs/[...path]/page.tsx", "app/shop/[[...filters]]/page.tsx"]);

        var output = await GenerateAsync(app);

        Assert.Contains(
            """
            export type RouteParams = {
              "/": Record<string, never>;
              "/about": Record<string, never>;
              "/blog/[slug]": { slug: string };
              "/docs/[...path]": { path: string[] };
              "/shop/[[...filters]]": { filters?: string[] };
            };
            """.ReplaceLineEndings("\n"),
            output);
        Assert.Contains("export type Route = '/' | '/about' | `/blog/${string}` | `/docs/${string}` | '/shop' | `/shop/${string}`;", output);
        Assert.Contains("export function route<P extends RoutePattern>(", output);
        Assert.Contains(
            """export const routePatterns = ["/", "/about", "/blog/[slug]", "/docs/[...path]", "/shop/[[...filters]]"] as const;""", output);
        Assert.Contains("export function isHref(value: string): value is Href {\n  return isRouteHref(value, routePatterns);\n}", output);
        Assert.Contains("export const Href = z.custom<Href>((value) => typeof value === 'string' && isHref(value), 'Not a URL this app serves');", output);
        Assert.Contains("declare module 'netjes' {\n  interface Register {\n    href: Href;\n  }\n}", output);
    }

    [Fact]
    public async Task Generate_RegisteredGroups_AreExported()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a => a.Services.GetRequiredService<TypeGenRegistry>()
                .Add("actions", "items.create", new Dictionary<string, Type> { ["input"] = typeof(NewItem), ["result"] = typeof(Item) }));

        var output = await GenerateAsync(app);

        Assert.Contains("export const actions = {\n  \"items.create\": { input: NewItem, result: Item },\n} as const;", output);
    }

    [Fact]
    public async Task Generate_DeferredProps_AreDeferredSchemasFromNetjesZod()
    {
        await using var app = await TestApp.StartAsync(
            ["app/posts/[slug]/page.tsx"],
            map: a => a.MapPageLoader("/posts/[slug]", (string slug) =>
                Page.Props(new PostPageProps(new PostDetail(slug, "T"), Page.Defer(Task.FromResult<IReadOnlyList<PostSummary>>([]))))));

        var output = await GenerateAsync(app);

        Assert.Contains("import { deferred } from 'netjes/zod';\n", output);
        Assert.Contains("  related: deferred(z.array(PostSummary)),\n", output);
    }

    [Fact]
    public async Task Generate_WithoutDeferredProps_DoesNotImportNetjesZod()
    {
        await using var app = await TestApp.StartAsync(["app/page.tsx"]);

        Assert.DoesNotContain("netjes/zod", await GenerateAsync(app));
    }

    [Fact]
    public async Task Generate_LayoutLoaderProps_AreInTheLayoutsMapBySegment()
    {
        await using var app = await TestApp.StartAsync(
            ["app/layout.tsx", "app/docs/layout.tsx", "app/docs/page.tsx"],
            map: a => a.MapLayoutLoader("/docs", () => Page.Props(new DocsLayoutProps(["intro"]))));

        var output = await GenerateAsync(app);

        Assert.Contains("export const layouts = {\n  \"app/docs\": DocsLayoutProps,\n} as const;", output);
    }

    [Fact]
    public async Task Generate_ServerActions_AreTypedReferences()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a =>
            {
                a.MapAction("posts.like", (LikeInput input) =>
                    input.Slug.Length == 0 ? ServerAction.Invalid("slug", "Required") : ServerAction.Ok(new Likes(input.Slug, 1)));
                a.MapAction("guestbook.sign", ([FromForm] string name) => ServerAction.Ok());
            });

        var output = await GenerateAsync(app);

        Assert.Contains("import { buildHref, isRouteHref, serverAction, type SearchParamsInput } from 'netjes';", output);
        Assert.Contains("export const serverActions = {\n", output);
        Assert.Contains("  \"guestbook.sign\": serverAction<FormData, void>(\"guestbook.sign\"),\n", output);
        Assert.Contains("  \"posts.like\": serverAction<z.input<typeof LikeInput>, Likes>(\"posts.like\", { result: Likes }),\n", output);
    }

    [Fact]
    public async Task Generate_ActionInputs_AreWhatTheActionAccepts_NotWhatTheTypeWrites()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a =>
            {
                a.MapAction("posts.create", (CreatePost input) => ServerAction.Ok(new Likes(input.Title, 0)));
                a.MapAction("posts.like", (LikeInput input) => ServerAction.Ok(new Likes(input.Slug, 1)));
            });

        var output = await GenerateAsync(app);

        // Nullable and defaulted keys may be left out; a computed property is never read.
        Assert.Contains(
            "const actionInputs = {\n  \"posts.create\": z.object({ title: z.string(), subtitle: z.string().nullable().optional(), body: z.string().optional() }),\n} as const;",
            output);
        Assert.Contains(
            "  \"posts.create\": serverAction<z.input<typeof actionInputs[\"posts.create\"]>, Likes>(\"posts.create\", { result: Likes }),\n", output);
        // Where the two agree, the named schema reads better.
        Assert.Contains("  \"posts.like\": serverAction<z.input<typeof LikeInput>, Likes>(\"posts.like\", { result: Likes }),\n", output);
    }

    [Fact]
    public async Task Generate_ActionsWithAnonymousResults_AreTypedByTheResultSchema()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"], map: a => a.MapAction("posts.count", () => ServerAction.Ok(new { Total = 3 })));

        var output = await GenerateAsync(app);

        Assert.Contains("const actionResults = {\n  \"posts.count\": z.object({ total: z.number().int() }),\n} as const;", output);
        Assert.Contains(
            "  \"posts.count\": serverAction<void, z.infer<typeof actionResults[\"posts.count\"]>>(\"posts.count\", { result: actionResults[\"posts.count\"] }),\n",
            output);
    }

    [Fact]
    public async Task Generate_ActionsWithoutAResultOrAnInput_AreTypedVoid()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a =>
            {
                a.MapAction("auth.logout", (HttpContext http) => ServerAction.Redirect("/"));
                a.MapAction("posts.delete", ([FromForm] string slug) => slug.Length == 0 ? ServerAction.Invalid("slug", "Required") : ServerAction.Ok());
            });

        var output = await GenerateAsync(app);

        // ServerAction.Ok(), .Redirect(...) and the like send no result; an action that binds no input takes none.
        Assert.Contains("  \"auth.logout\": serverAction<void, void>(\"auth.logout\"),\n", output);
        Assert.Contains("  \"posts.delete\": serverAction<FormData, void>(\"posts.delete\"),\n", output);
    }

    [Fact]
    public async Task Generate_IsDeterministic()
    {
        await using var app = await TestApp.StartAsync(
            ["app/blog/[slug]/page.tsx"], map: a => a.MapPageLoader("/blog/[slug]", (string slug) => Page.Props(new PostProps(new PostDetail(slug, "T")))));

        Assert.Equal(await GenerateAsync(app), await GenerateAsync(app));
    }
}
