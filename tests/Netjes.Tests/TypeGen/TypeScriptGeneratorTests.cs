    [Fact]
    public async Task Generate_EndpointUrl_UsesTemplatesThatRouteTheSameWay()
    {
        await using var app = await TestApp.StartAsync(
            ["app/about/page.tsx", "app/docs/[...path]/page.tsx"],
            map: a =>
            {
                a.MapGroup("/api/posts/{slug}/likes").MapGet("/", (string slug) => TypedResults.Ok(new Likes(slug, 1)));
                a.MapMethods("/docs/{**path:regex(\\.md$)}", [HttpMethods.Get, HttpMethods.Head], (string path) => Results.Text(path)).WithOrder(-1);
                a.MapGet("/opt/{id?}", (int? id) => $"{id}");
                a.MapGet("/raw/{*rest}", (string? rest) => rest ?? "");
                a.MapGet("/list/{page:int=1}", (int page) => $"{page}");
                a.MapGet("/files/{name}.{ext?}", (string name, string? ext) => name);
                a.MapGet("/a{{b}}/{id}", (string id) => id);
                a.MapGet("/100%/{id}", (string id) => id);
                a.MapGet("/c#/{id}", (string id) => id);
                a.MapGet("/a\\b", () => "a");
                a.MapGet("/", () => "home");
            });

        var output = await GenerateAsync(app);

        // As the matcher reads them: without constraints or a trailing slash, which it ignores, and with a literal's
        // braces encoded, so that only a value's braces are left. So are the characters a browser reads otherwise in
        // a path: % starts an escape, # the fragment, and \ is read as /.
        Assert.Contains(
            """
            const endpointTemplates: Record<EndpointKey, string> = {
              "GET /": "/",
              "GET /100%/{id}": "/100%25/{id}",
              "GET /a\\b": "/a%5Cb",
              "GET /api/posts/{slug}/likes/": "/api/posts/{slug}/likes",
              "GET /a{{b}}/{id}": "/a%7Bb%7D/{id}",
              "GET /c#/{id}": "/c%23/{id}",
              "GET /docs/{**path:regex(\\.md$)}": "/docs/{**path}",
              "GET /files/{name}.{ext?}": "/files/{name}.{ext?}",
              "GET /list/{page:int=1}": "/list/{page=1}",
              "GET /opt/{id?}": "/opt/{id?}",
              "GET /raw/{*rest}": "/raw/{*rest}",
            };
            """.ReplaceLineEndings("\n"),
            output);
        // An MVC attribute route has no leading slash.
        Assert.Equal("/api/Products/{id}", EndpointUrls.Template(RoutePatternFactory.Parse("api/Products/{id:int}")));
    }

