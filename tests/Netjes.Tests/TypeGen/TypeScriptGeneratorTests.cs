    [Fact]
    public async Task Generate_EndpointUrls_TypeTheRouteValuesAndQueryParametersEachEndpointBinds()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a =>
            {
                a.MapGet("/api/search", (string? q, int? take, [Range(1, 50)] int size = 10) => TypedResults.Ok(new Item(size, q ?? "")));
                a.MapGet("/api/items/{id}", (int id, [FromQuery(Name = "v")] int version, [FromHeader(Name = "X-Trace")] string? trace) =>
                    TypedResults.Ok(new Item(id, $"{version}")));
                a.MapGet("/api/posts/{slug}/comments/{n:int}", ([FromRoute(Name = "slug")] string post, int n) => TypedResults.Ok(new Item(n, post)));
                a.MapGet("/api/filter", ([AsParameters] ItemFilter filter) => TypedResults.Ok(new Item(filter.Page, filter.Q ?? "")));
                a.MapGet("/api/tags", (string[] tags, DateOnly? since) => TypedResults.Ok(tags));
                a.MapGet("/api/paged", (Paging paging) => TypedResults.Ok(new Item(paging.Page, "")));
                a.MapGet("/api/page", ([FromQuery(Name = "page[size]")] int? size, StringValues sort) => TypedResults.Ok(new Item(size ?? 0, $"{sort}")));
                // A HEAD asks for no body: the JSON endpoint has a key for its GET only.
                a.MapMethods("/api/status", [HttpMethods.Get, HttpMethods.Head], () => TypedResults.Ok(new Item(1, "up")));
                a.MapPost("/api/items", (NewItem item, HttpContext http, CancellationToken cancellationToken) =>
                    TypedResults.Created("/api/items/1", new Item(1, item.Name)));
                // On a POST, minimal APIs read an array from the JSON body.
                a.MapPost("/api/items/bulk", (string[] ids, ClaimsPrincipal user) => TypedResults.Ok(ids.Length));
            });

        var output = await GenerateAsync(app);

        // Route values first, then the query values the handler binds; headers, bodies, services and a type that binds
        // itself read nothing a URL builder can name.
        Assert.Contains(
            """
            export type EndpointParams = {
              "GET /api/filter": { Q?: string | null | undefined; Page?: number | null | undefined };
              "GET /api/items/{id}": { id: number; v: number };
              "GET /api/page": { "page[size]"?: number | null | undefined; sort?: string | readonly string[] | null | undefined };
              "GET /api/paged": Record<string, never>;
              "GET /api/posts/{slug}/comments/{n:int}": { slug: string; n: number };
              "GET /api/search": { q?: string | null | undefined; take?: number | null | undefined; size?: number | null | undefined };
              "GET /api/status": Record<string, never>;
              "GET /api/tags": { tags?: readonly string[] | null | undefined; since?: string | null | undefined };
              "POST /api/items": Record<string, never>;
              "POST /api/items/bulk": Record<string, never>;
            };
            export type EndpointKey = keyof EndpointParams;
            """.ReplaceLineEndings("\n"),
            output);
        Assert.Contains("[params?: EndpointParams[K], search?: SearchParamsInput]", output);
        Assert.Contains("[params: EndpointParams[K], search?: SearchParamsInput]", output);
        Assert.Contains("return buildEndpointUrl(endpointTemplates[key], args[0] ?? {}, args[1], key);", output);
        // After the api map, whose keys it shares.
        Assert.True(output.IndexOf("export const api = ", StringComparison.Ordinal) < output.IndexOf("export type EndpointParams = ", StringComparison.Ordinal));
    }

    [Fact]
    public async Task Generate_EndpointUrls_TakeRouteOptionalityFromTheTemplate()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a =>
            {
                // The template needs a value however the handler declares it.
                a.MapGet("/opt/{slug}", (string? slug) => slug ?? "");
                // Without a value, binding answers 400 for these, and the URL is no use. The analyzer warns about the
                // first, which an app that does not treat warnings as errors builds all the same.
#pragma warning disable ASP0007
                a.MapGet("/id/{id?}", (int id) => $"{id}");
#pragma warning restore ASP0007
                a.MapGet("/cat/{**path}", (string path) => path);
                a.MapGet("/maybe/{id?}", (int? id) => $"{id}");
                a.MapGet("/any/{**path}", (string? path) => path ?? "");
                // Routing fills in the default.
                a.MapGet("/page/{page=1}", (int page) => $"{page}");
                // Nothing binds it, so it is a string the template makes optional.
                a.MapGet("/raw/{id?}", (HttpContext http) => "raw");
            });

        var output = await GenerateAsync(app);

        Assert.Contains(
            """
            export type EndpointParams = {
              "GET /any/{**path}": { path?: string | null | undefined };
              "GET /cat/{**path}": { path: string };
              "GET /id/{id?}": { id: number };
              "GET /maybe/{id?}": { id?: number | null | undefined };
              "GET /opt/{slug}": { slug: string };
              "GET /page/{page=1}": { page?: number | null | undefined };
              "GET /raw/{id?}": { id?: string | null | undefined };
            };
            """.ReplaceLineEndings("\n"),
            output);
    }

