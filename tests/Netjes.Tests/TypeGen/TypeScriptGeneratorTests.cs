    public async Task Generate_ActionsWithAnonymousResults_AreTypedByTheResultSchema()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"], map: a => a.MapAction("posts.count", () => ServerAction.Ok(new { Total = 3 })));

        var output = await GenerateAsync(app);

        Assert.Contains("const actionResults = {\n  \"posts.count\": z.object({ total: z.number().int() }),\n} as const;", output);
        Assert.Contains(
            "  \"posts.count\": serverAction<void, z.infer<typeof actionResults[\"posts.count\"]>>(\"posts.count\", { result: actionResults[\"posts.count\"] }),\n",
            output);
    }

    [Fact]
    public async Task Generate_ActionsWithoutAResultOrAnInput_AreTypedVoid()
    {
        await using var app = await TestApp.StartAsync(
            ["app/page.tsx"],
            map: a =>
            {
                a.MapAction("auth.logout", (HttpContext http) => ServerAction.Redirect("/"));
                a.MapAction("posts.delete", ([FromForm] string slug) => slug.Length == 0 ? ServerAction.Invalid("slug", "Required") : ServerAction.Ok());
            });

        var output = await GenerateAsync(app);

        // ServerAction.Ok(), .Redirect(...) and the like send no result; an action that binds no input takes none.
        Assert.Contains("  \"auth.logout\": serverAction<void, void>(\"auth.logout\"),\n", output);
        Assert.Contains("  \"posts.delete\": serverAction<FormData, void>(\"posts.delete\"),\n", output);
    }

